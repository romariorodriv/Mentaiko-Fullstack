-- SCRUM-25: objetivo de días de registro por semana (lunes a domingo).
CREATE TABLE IF NOT EXISTS weekly_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    target_days SMALLINT NOT NULL CHECK (target_days BETWEEN 1 AND 7),
    CONSTRAINT uk_weekly_goals_user_week UNIQUE(user_id, week_start),
    CONSTRAINT ck_weekly_goals_monday CHECK(EXTRACT(ISODOW FROM week_start) = 1)
);

-- SCRUM-28: una noche por usuario y fecha de despertar en Lima.
CREATE TABLE IF NOT EXISTS sleep_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entry_date DATE NOT NULL,
    hours NUMERIC(4,2) NOT NULL CHECK (hours >= 0 AND hours <= 24 AND hours * 4 = FLOOR(hours * 4)),
    quality SMALLINT NOT NULL CHECK (quality BETWEEN 1 AND 5),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sleep_user_date UNIQUE (user_id, entry_date)
);
CREATE INDEX IF NOT EXISTS ix_sleep_user_date ON sleep_entries(user_id, entry_date DESC);

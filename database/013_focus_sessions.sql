CREATE TABLE IF NOT EXISTS focus_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    activity_id BIGINT NOT NULL REFERENCES micro_activities(id),
    recommendation_id BIGINT REFERENCES activity_recommendations(id) ON DELETE SET NULL,
    request_id UUID NOT NULL,
    duration_seconds INTEGER NOT NULL,
    completed_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_focus_sessions_user_request UNIQUE (user_id, request_id),
    CONSTRAINT ck_focus_sessions_duration CHECK (duration_seconds BETWEEN 60 AND 7200)
);

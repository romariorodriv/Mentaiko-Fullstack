-- SCRUM-29: energía única por día de negocio y usuario.
CREATE TABLE IF NOT EXISTS energy_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entry_date DATE NOT NULL,
    level SMALLINT NOT NULL CHECK (level BETWEEN 1 AND 5),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_energy_user_date UNIQUE (user_id, entry_date)
);
CREATE INDEX IF NOT EXISTS ix_energy_user_date ON energy_entries(user_id, entry_date DESC);

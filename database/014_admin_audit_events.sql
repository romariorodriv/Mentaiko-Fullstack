-- SCRUM-38 / HU-34: Append-only audit events for committed administrative mutations.
-- Apply manually before deploying the matching backend; never alter prod automatically.
CREATE TABLE IF NOT EXISTS admin_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL,
    action VARCHAR(12) NOT NULL CHECK (action IN ('CREATE','UPDATE')),
    resource_type VARCHAR(24) NOT NULL CHECK (resource_type IN ('EMOTION','MICRO_ACTIVITY','RULE')),
    resource_id BIGINT NOT NULL,
    before_summary VARCHAR(500),
    after_summary VARCHAR(500) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_admin_audit_occurred ON admin_audit_events(occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_admin_audit_resource ON admin_audit_events(resource_type, resource_id, occurred_at DESC);
-- actor_user_id intentionally has no FK, so administrative history survives account deletion.
-- Summaries must be allowlisted metadata only; never passwords, notes, bearer tokens or emails.
